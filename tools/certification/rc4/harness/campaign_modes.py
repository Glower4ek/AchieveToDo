"""Select the progression config (threshold mode) of a prepared campaign runtime.

Usage: campaign_modes.py <campaignNN> <easy|normal|hard|chaos|path/to/custom.toml>
The plugin reads plugins/AchieveToDo/progression/world-selection.properties (configName) at startup.
Built-in modes are generated by the plugin itself when -Dachievetodo.progression.freshConfig=true;
a custom config is copied to configs/<stem>.toml and selected by that name. Restart the server after.
campaign.py then takes thresholds from the selected file (campaign.active_thresholds).
"""
import json, re, shutil, sys
from pathlib import Path

BUILT_IN = ('easy', 'normal', 'hard', 'chaos')
FRESH = '-Dachievetodo.progression.freshConfig=true'


INITIAL = '-Dachievetodo.progression.initialConfig='


def set_mode(a: Path, mode: str):
    prog = a / 'runtime' / 'plugins' / 'AchieveToDo' / 'progression'
    launch = json.loads((a / 'PRELAUNCH.json').read_text(encoding='utf8')).get('launch', 'explicit')
    if launch == 'release' and mode.lower() in BUILT_IN:
        # rc.2 review: the operator way to a non-default preset is a fresh install started once with
        # -Dachievetodo.progression.initialConfig=<preset> (STARTING_THE_SERVER.md). The plugin then writes
        # world-group.properties, world-selection.properties and the preset itself; no freshConfig flag.
        for f in ('world-group.properties', 'world-selection.properties'):
            (prog / f).unlink()
        args_file = a / 'runtime_args.json'
        args = json.loads(args_file.read_text())
        args['args'] = [v for v in args['args'] if v != FRESH and not v.startswith(INITIAL)]
        first_agent = next(i for i, v in enumerate(args['args']) if v.startswith('-javaagent:'))
        args['args'].insert(first_agent, INITIAL + mode.lower())
        args_file.write_text(json.dumps(args, indent=2))
        return mode.lower()
    if mode.lower() in BUILT_IN:
        name = mode.lower()
    else:
        source = Path(mode)
        name = source.stem
        assert re.fullmatch(r'[A-Za-z0-9_-]+', name) and name.lower() not in BUILT_IN, name
        shutil.copy2(source, prog / 'configs' / f'{name}.toml')
    selection = prog / 'world-selection.properties'
    lines = selection.read_text(encoding='utf8').splitlines()
    assert sum(l.startswith('configName=') for l in lines) == 1
    selection.write_text('\n'.join(f'configName={name}' if l.startswith('configName=') else l for l in lines) + '\n', encoding='utf8')
    args_file = a / 'runtime_args.json'
    args = json.loads(args_file.read_text())
    args['args'] = [v for v in args['args'] if v != FRESH]
    if name in BUILT_IN:
        # Insert before the agents so it is a plain system property like the other product flags.
        first_agent = next(i for i, v in enumerate(args['args']) if v.startswith('-javaagent:'))
        args['args'].insert(first_agent, FRESH)
    args_file.write_text(json.dumps(args, indent=2))
    return name


if __name__ == '__main__':
    root = Path(__file__).parent
    print('mode', set_mode(root / sys.argv[1], sys.argv[2]))
