"""Explicit network-only selected-input provisioning; never relaxes build gates.

Gradle is an external tool, not a hidden dependency cache. Binary acquisition uses
group-scoped HTTPS and immutable historical pins. Local Gradle descriptors must
be generated by Gradle from upstream metadata and match their original pins.
"""
from pathlib import Path
import argparse, concurrent.futures, hashlib, json, os, subprocess, time, urllib.request
from r7_bootstrap import selected, target, require

REPOS = {'c5f7e3fe759bfc29dcb6fc6baddbbc5f': ('fabric', 'https://maven.fabricmc.net/'),
         '6a010b6427d0fbb530f9fb3ff541bac8': ('mojang', 'https://libraries.minecraft.net/'),
         '26c913274550a0b2221f47a0fe2d2358': ('central', 'https://repo.maven.apache.org/maven2/')}

def identity(p):
    with Path(p).open('rb') as f:
        return {'bytes': Path(p).stat().st_size, 'sha256': hashlib.file_digest(f, 'sha256').hexdigest()}

def expected(r): return {'bytes': r['size'], 'sha256': r['SHA256']}

class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs): raise ValueError('REDIRECT_REFUSED')

def acquire(r, home):
    group = r['group']
    origin = ('https://maven.fabricmc.net/' if group.startswith('net.fabricmc') else
              'https://libraries.minecraft.net/' if group == 'com.mojang' else
              'https://repo.maven.apache.org/maven2/')
    url = origin + group.replace('.', '/') + '/' + r['module'] + '/' + r['version'] + '/' + r['file']
    p = target(home, r['gradleUserHomeRelativePath'])
    row = {'path': r['gradleUserHomeRelativePath'], 'url': url, 'expected': expected(r)}
    try:
        if p.exists():
            require(identity(p) == expected(r), 'DESTINATION_COLLISION')
            return {**row, 'status': 'PASS', 'origin': 'VERIFIED_RESUME'}
        with urllib.request.build_opener(NoRedirect).open(url, timeout=30) as q:
            b = q.read(r['size'] + 1)
            require(q.geturl() == url, 'ORIGIN_CHANGED')
            require(len(b) == r['size'] and hashlib.sha256(b).hexdigest() == r['SHA256'], 'CONTENT_IDENTITY')
        p.parent.mkdir(parents=True, exist_ok=True)
        part = p.with_name(p.name + '.r8-part')
        require(not part.exists(), 'UNEXPECTED_PARTIAL_FILE')
        with part.open('xb') as f:
            f.write(b); f.flush(); os.fsync(f.fileno())
        os.replace(part, p)
        return {**row, 'status': 'PASS', 'origin': 'FRESH_HTTPS', 'actual': identity(p)}
    except Exception as ex:
        return {**row, 'status': 'FAIL', 'error': type(ex).__name__ + ':' + str(ex)}

def verify(source, home):
    rows = []
    for r in selected(source):
        p = target(home, r['gradleUserHomeRelativePath'])
        actual = identity(p) if p.is_file() else None
        rows.append({'path': r['gradleUserHomeRelativePath'], 'expected': expected(r),
                     'actual': actual, 'match': actual == expected(r)})
    return {'matched': sum(r['match'] for r in rows), 'total': 372, 'results': rows}

def reconstruct(source, home, work, gradle, output):
    work.mkdir(parents=True, exist_ok=True)
    (work/'settings.gradle').write_text("rootProject.name='r8-network-descriptors'\ninclude 'fabric','mojang','central'\n", encoding='utf8')
    (work/'build.gradle').write_text("tasks.register('reconstruct') { dependsOn subprojects.collect { it.tasks.named('reconstruct') } }\n", encoding='utf8')
    for key, (name, url) in REPOS.items():
        sub = work/name; sub.mkdir(exist_ok=True)
        coords = sorted({':'.join([r['group'], r['module'], r['version']]) for r in selected(source)
                         if r['file'] == 'descriptor.bin' and r['gradleUserHomeRelativePath'].split('/')[-2] == key
                         and not target(home, r['gradleUserHomeRelativePath']).exists()})
        metadata = 'metadataSources { mavenPom(); artifact(); ignoreGradleMetadataRedirection() }' if name == 'mojang' else ''
        code = "repositories { maven { url = '" + url + "'; " + metadata + " }; mavenCentral() }\n"
        code += 'def selected = ' + json.dumps(coords) + '''
tasks.register('reconstruct') { doLast { selected.each { coordinate ->
 def c = configurations.detachedConfiguration(dependencies.create(coordinate)); c.transitive = false
 c.attributes { attribute(org.gradle.api.attributes.Usage.USAGE_ATTRIBUTE, objects.named(org.gradle.api.attributes.Usage, org.gradle.api.attributes.Usage.JAVA_RUNTIME)); attribute(org.gradle.api.attributes.Bundling.BUNDLING_ATTRIBUTE, objects.named(org.gradle.api.attributes.Bundling, org.gradle.api.attributes.Bundling.EXTERNAL)); attribute(org.gradle.api.attributes.Category.CATEGORY_ATTRIBUTE, objects.named(org.gradle.api.attributes.Category, org.gradle.api.attributes.Category.LIBRARY)) }
 def result = c.incoming.resolutionResult
 def failures = result.allDependencies.findAll { it instanceof org.gradle.api.artifacts.result.UnresolvedDependencyResult }
 if (!failures.empty) throw new GradleException('R8_METADATA_FAILURE '+coordinate+' '+failures.collect { it.failure.toString() })
 println('R8_METADATA_RESOLVED '+coordinate)
} } }
'''
        (sub/'build.gradle').write_text(code, encoding='utf8')
    (work/'gradle').mkdir(exist_ok=True)
    (work/'gradle/verification-metadata.xml').write_bytes((source/'gradle/verification-metadata.xml').read_bytes())
    tmp = work/'tmp'; tmp.mkdir(exist_ok=True)
    # Windows IPv6 routing caused the demonstrated Java transport failures.
    # HTTPS/SNI/CA validation and repository cache identities stay unchanged.
    env = {**os.environ, 'GRADLE_USER_HOME': str(home), 'TEMP': str(tmp), 'TMP': str(tmp),
           'JAVA_TOOL_OPTIONS': '-Djava.net.preferIPv4Stack=true'}
    cmd = [str(gradle), '--no-daemon', '--no-watch-fs', '--dependency-verification', 'strict',
           '--console=plain', '--max-workers=2', '-p', str(work), 'reconstruct']
    start = time.monotonic()
    with (output/'gradle.log').open('w', encoding='utf8') as log:
        proc = subprocess.Popen(cmd, cwd=work, env=env, stdout=log, stderr=subprocess.STDOUT)
        (output/'active-process.json').write_text(json.dumps({'pid': proc.pid, 'command': cmd}), encoding='utf8')
        try: code = proc.wait(timeout=900)
        except subprocess.TimeoutExpired:
            subprocess.run(['taskkill','/PID',str(proc.pid),'/T','/F'], capture_output=True); code = 'TIMEOUT'
    return {'command': cmd, 'exitCode': code, 'seconds': time.monotonic()-start,
            'transport': 'IPv4; default CA and HTTPS verification retained'}

def main():
    p = argparse.ArgumentParser()
    for n in ['source','home','work','output','gradle','gradle-sha256']: p.add_argument('--'+n, required=True)
    a = p.parse_args(); source,home,work,output,gradle = [Path(getattr(a,n)).absolute() for n in ['source','home','work','output','gradle']]
    require(identity(gradle)['sha256'] == a.gradle_sha256, 'GRADLE_LAUNCHER_IDENTITY')
    require(not home.resolve().is_relative_to(source.resolve()), 'EXTERNAL_HOME_REQUIRED')
    require(len({home.resolve(),work.resolve(),output.resolve()}) == 3, 'DISTINCT_DIRECTORIES_REQUIRED')
    rows = selected(source); home.mkdir(parents=True,exist_ok=True);output.mkdir(parents=True,exist_ok=True)
    before = verify(source,home)
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        downloads = list(pool.map(lambda r: acquire(r,home), [r for r in rows if r['file'] != 'descriptor.bin']))
    (output/'downloads.json').write_text(json.dumps(downloads,indent=2),encoding='utf8')
    require(all(r['status']=='PASS' for r in downloads), 'ACQUISITION_FAILED_SEE_DOWNLOADS')
    run = reconstruct(source,home,work,gradle,output)
    result = {**verify(source,home), 'beforeMatched': before['matched'], 'run': run,
              'gradleLauncher': identity(gradle), 'offlineBundleUsed': False,
              'sourceManifest': identity(source/'src/test/resources/build_inputs/manifest.json')}
    (output/'verification.json').write_text(json.dumps(result,indent=2),encoding='utf8')
    require(run['exitCode']==0 and result['matched']==372, 'INCOMPLETE_372')
    print('R8_NETWORK_372_PASS')

if __name__ == '__main__': main()
