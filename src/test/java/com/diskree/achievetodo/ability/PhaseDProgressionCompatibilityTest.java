    @BeforeAll
    static void bootstrap() { SharedConstants.tryDetectVersion(); Bootstrap.bootStrap(); }

    public static void verifyOldPresets() {
        List<Map<AbilityType, Integer>> actual = List.of(Progressions.getEasyProgression(),
            Progressions.getNormalProgression(), Progressions.getHardProgression());
        List<String> rows = OLD_PRESETS.lines().map(String::trim).filter(s -> !s.isEmpty()).toList();
        assertEquals(151, rows.size());
        for (int preset = 0; preset < 3; preset++) {
            Map<AbilityType, Integer> expected = new HashMap<>();
            for (String row : rows) {
                String[] values = row.split(" ");
                expected.put(AbilityType.valueOf(values[0]), Integer.parseInt(values[preset + 1]));
            }
            assertEquals(expected, actual.get(preset).entrySet().stream()
                .filter(e -> expected.containsKey(e.getKey()))
                .collect(java.util.stream.Collectors.toMap(Map.Entry::getKey, Map.Entry::getValue)));
        }
    }

    @Test
    void all453OriginalPresetValuesAreUnchanged() { verifyOldPresets(); }

    @Test
    void callersCannotMutateAnotherPresetRead() {
        Map<AbilityType, Integer> easy = Progressions.getEasyProgression();
        Map<AbilityType, Integer> normal = Progressions.getNormalProgression();
        easy.put(AbilityType.OPEN_CHEST, -1);
        assertEquals(42, normal.get(AbilityType.OPEN_CHEST));
        assertEquals(40, Progressions.getEasyProgression().get(AbilityType.OPEN_CHEST));
    }
